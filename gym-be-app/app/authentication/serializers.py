class LoginSerializer(serializers.ModelSerializer):
    email = serializers.EmailField(max_length=255, min_length=3, required=False)
    password = serializers.CharField(
        max_length=68, min_length=6, write_only=True)
    username = serializers.CharField(
        max_length=255, min_length=3, required=False)

    name = serializers.CharField(read_only=True)
    surname = serializers.CharField(read_only=True)
    gender = serializers.CharField(read_only=True)
    is_coatch = serializers.BooleanField(read_only=True)
    is_admin = serializers.BooleanField(read_only=True)
    is_subscription = serializers.BooleanField(read_only=True)

    tokens = serializers.SerializerMethodField()

    def get_tokens(self, obj):
        user = User.objects.get(email=obj['email'])

        return {
            'refresh': user.tokens()['refresh'],
            'access': user.tokens()['access']
        }

    class Meta:
        model = User
        fields = ['email', 'password', 'username', 'name', 'surname', 'gender', 'is_coatch', 'is_admin', 'tokens', 'is_subscription']

    def validate(self, attrs):
        email = attrs.get('email', '')
        password = attrs.get('password', '')
        if not email:
            filtered_user_by_username = User.objects.filter(username=attrs.get('username', ''))
            if len(filtered_user_by_username):
                email = filtered_user_by_username[0].email
        filtered_user_by_email = User.objects.filter(email=email)
        user = auth.authenticate(email=email, password=password)

        if filtered_user_by_email.exists() and filtered_user_by_email[0].auth_provider != 'email':
            raise AuthenticationFailed(
                detail='Please continue your login using ' + filtered_user_by_email[0].auth_provider)

        if not user:
            raise AuthenticationFailed('Invalid credentials, try again')
        if not user.is_active:
            raise AuthenticationFailed('Account disabled, contact admin')
        if not user.is_verified:
            raise AuthenticationFailed('Email is not verified')
        
        is_subscription = False if user.id_subscription is None else True

        return {
            'email': user.email,
            'username': user.username,
            'name': user.name,
            'surname': user.surname,
            'gender': user.gender,
            'is_coatch': user.is_trainer,
            'is_admin': user.is_staff,
            'is_subscription': is_subscription,
            'tokens': user.tokens
        }

        return super().validate(attrs)


